import { test, expect } from '@playwright/test'
import { initializeTestEnvironment } from '@firebase/rules-unit-testing'
import { doc, getDoc, setDoc } from 'firebase/firestore'
import { readFile } from 'node:fs/promises'

test('platform links a business, administrator selects it, suspension and archival are reversible', async ({ page, browser }) => {
  test.setTimeout(120000)
  const id = `businesses-${Date.now()}`, password = 'Test-password-123!'
  const env = await initializeTestEnvironment({ projectId: 'demo-citaspro', firestore: { host: '127.0.0.1', port: 8080, rules: await readFile('firestore.rules', 'utf8') } })
  const accounts = {}
  for (const role of ['platform', 'admin']) {
    const email = `${role}-${id}@example.test`
    const response = await fetch('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signUp?key=demo-key', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email, password, returnSecureToken: true }) })
    expect(response.ok).toBe(true)
    const { localId } = await response.json()
    accounts[role] = { uid: localId, email }
  }
  const adminContext = await browser.newContext(), admin = await adminContext.newPage()
  async function login(target, email) {
    await target.goto('/login'); await target.getByLabel('Correo electrónico').fill(email)
    await target.getByLabel('Contraseña', { exact: true }).fill(password)
    await target.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
    await expect(target).toHaveURL(/dashboard/)
  }
  try {
    await env.withSecurityRulesDisabled(async context => {
      const db = context.firestore()
      await setDoc(doc(db, 'businesses', id), { name: 'Negocio anterior', ownerUserId: accounts.admin.uid, status: 'active', settings: { publicPageEnabled: false } })
      for (const [role, account] of Object.entries(accounts)) {
        await setDoc(doc(db, 'users', account.uid), { email: account.email, firstName: role, lastName: 'Test', status: 'active', globalRole: role === 'platform' ? 'superadmin' : 'user', businessIds: [id], onboardingComplete: true })
        await setDoc(doc(db, 'memberships', `${id}_${account.uid}`), { userId: account.uid, businessId: id, role: 'admin', status: 'active' })
      }
    })
    await login(page, accounts.platform.email)
    await page.getByRole('link', { name: 'Negocios', exact: true }).click()
    await page.getByRole('button', {name:'Crear negocio',exact:true}).click()
    await page.getByLabel('Nombre del negocio', { exact: true }).fill('Consultorio nuevo')
    await page.getByRole('button',{name:'Continuar',exact:true}).click()
    await page.getByLabel('Cuenta del administrador').selectOption('existing')
    await page.getByLabel('Correo del administrador').fill(accounts.admin.email)
    await page.getByRole('button', {name:'Continuar',exact:true}).click()
    await page.getByRole('button', { name: 'Crear y vincular negocio' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Negocio creado y vinculado' })).toBeVisible()
    await login(admin, accounts.admin.email)
    await admin.getByRole('link', { name: 'Configuración', exact: true }).click()
    await expect(admin.getByLabel('Nombre', { exact: true })).toHaveValue('Consultorio nuevo')
    await expect(admin.getByLabel('Nombre', { exact: true })).toBeDisabled()
    await expect(admin.getByLabel('Color primario')).toBeDisabled()
    await admin.getByLabel('Descripción', { exact: true }).fill('Atención con cita previa')
    await admin.getByRole('link', { name:'Dashboard', exact:true }).click()
    await expect(admin.getByRole('alertdialog')).toBeVisible()
    await expect(admin.getByRole('alertdialog')).toContainText('Tienes cambios sin guardar')
    await admin.getByRole('alertdialog').getByRole('button', { name: 'Cancelar' }).click()
    await expect(admin).toHaveURL(/negocio$/)
    await admin.getByLabel('Publicar página del negocio').check()
    await admin.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
    await expect(admin.getByText('Cambios guardados.', { exact: true })).toBeVisible()
    await admin.getByRole('link', { name:'Dashboard', exact:true }).click()
    await expect(admin).toHaveURL(/dashboard$/)
    await expect(admin.getByRole('region', { name:'Pendientes de atención' })).toBeVisible()
    await admin.getByRole('link', { name:'Configuración', exact:true }).click()
    const activeBusinessId = (await admin.getByRole('link', { name: 'Ver página pública' }).getAttribute('href')).split('/').pop()
    await page.getByRole('link', { name: 'Seguridad y auditoría', exact: true }).click()
    await expect(page.locator('.platform-audit-list').getByText('Configuración del negocio actualizada', { exact:true }).first()).toBeVisible()
    await page.getByRole('link', { name: 'Negocios', exact: true }).click()
    await admin.getByRole('tab', { name: 'Contacto', exact: true }).click()
    const locationMap = admin.getByRole('application', { name: /Mapa OpenStreetMap/ })
    await expect(locationMap).toBeVisible()
    await locationMap.click({ position: { x: 140, y: 120 } })
    const latitude = admin.getByLabel('Latitud del mapa')
    const longitude = admin.getByLabel('Longitud del mapa')
    await expect(latitude).not.toHaveValue('')
    await expect(longitude).not.toHaveValue('')
    const marker = admin.locator('.leaflet-marker-icon')
    await expect(marker).toBeVisible()
    await expect(marker.locator('svg')).toBeVisible()
    const previousLatitude = await latitude.inputValue()
    const markerBox = await marker.boundingBox()
    await admin.mouse.move(markerBox.x + markerBox.width / 2, markerBox.y + markerBox.height / 2)
    await admin.mouse.down()
    await admin.mouse.move(markerBox.x + markerBox.width / 2 + 16, markerBox.y + markerBox.height / 2 + 12)
    await admin.mouse.up()
    await expect(latitude).not.toHaveValue(previousLatitude)
    await admin.getByLabel('Dirección', { exact: true }).fill('Calle de prueba 123')
    await admin.getByLabel('Ciudad', { exact: true }).fill('La Paz')
    await admin.getByLabel('País (código ISO)').fill('BO')
    await admin.getByRole('button', { name: 'Guardar ubicación' }).click()
    await expect(admin.getByRole('status').filter({ hasText: 'Ubicación guardada' }).first()).toBeVisible()
    let savedBusiness
    await env.withSecurityRulesDisabled(async context => { savedBusiness = await getDoc(doc(context.firestore(), 'businesses', activeBusinessId)) })
    expect(savedBusiness.data().location.addressLine).toBe('Calle de prueba 123')
    expect(savedBusiness.data().location.city).toBe('La Paz')
    expect(savedBusiness.data().location.latitude).toBe(Number(await latitude.inputValue()))
    expect(savedBusiness.data().location.longitude).toBe(Number(await longitude.inputValue()))
    await admin.setViewportSize({width:390,height:844})
    expect(await admin.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await expect(locationMap).toBeVisible()
    await admin.setViewportSize({width:1280,height:720})
    await page.setViewportSize({width:390,height:844})
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({path:'test-results/platform-polish-mobile.png',fullPage:true,animations:'disabled'})
    await page.setViewportSize({width:1280,height:720})
    await admin.getByRole('tab', { name: 'Datos generales', exact: true }).click()
    await admin.getByLabel('Descripción', {exact:true}).fill('Borrador no guardado')
    await admin.getByRole('link', {name:'Dashboard',exact:true}).click()
    await admin.getByRole('alertdialog').getByRole('button', { name: 'Descartar cambios' }).click()
    await expect(admin).toHaveURL(/dashboard$/)
    await admin.getByRole('link', {name:'Configuración',exact:true}).click()
    await expect(admin.getByLabel('Descripción', {exact:true})).toHaveValue('Atención con cita previa')
    await admin.setViewportSize({width:390,height:844})
    expect(await admin.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await admin.screenshot({path:'test-results/admin-settings-mobile.png',fullPage:true,animations:'disabled'})
    await admin.setViewportSize({width:1280,height:720})
    const card = page.locator('article').filter({ has: page.getByRole('heading', { name: 'Consultorio nuevo', exact: true }) })
    await card.getByRole('button', { name: 'Desactivar', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Desactivar negocio' }).click()
    await expect(admin.getByRole('alert')).toContainText('desactivado')
    await card.getByRole('button', { name: 'Eliminar', exact: true }).click()
    await page.getByLabel('Escribe Consultorio nuevo').fill('Consultorio nuevo')
    await page.getByRole('button', { name: 'Confirmar eliminación' }).click()
    await expect(card).toHaveCount(0)
    await page.getByLabel('Incluir archivados').check()
    await expect(card).toContainText('archivado')
    await card.getByRole('button', { name: 'Activar / restaurar' }).click()
    await expect(admin.getByLabel('Descripción', { exact: true })).toHaveValue('Atención con cita previa')
    await admin.getByLabel('Seleccionar negocio').selectOption(id)
    await expect(admin.getByLabel('Nombre', { exact: true })).toHaveValue('Negocio anterior')
    await page.screenshot({ path: 'test-results/platform-businesses.png', fullPage: true })
    await page.getByRole('button',{name:'Crear negocio',exact:true}).click()
    await page.getByLabel('Nombre del negocio', { exact: true }).fill('Negocio con cuenta nueva')
    await page.getByRole('button',{name:'Continuar',exact:true}).click()
    await page.getByLabel('Cuenta del administrador').selectOption('new')
    await page.getByLabel('Nombre del administrador', { exact: true }).fill('Nueva')
    await page.getByLabel('Apellido del administrador').fill('Administradora')
    const newEmail = `new-${id}@example.test`
    await page.getByLabel('Correo del administrador').fill(newEmail)
    await page.getByRole('button', {name:'Continuar',exact:true}).click()
    await page.getByRole('button', { name: 'Crear y vincular negocio' }).click()
    const secret = page.locator('code')
    await expect(secret).toBeVisible()
    const initialPassword = await secret.innerText()
    await expect(page.locator('article').filter({ hasText: 'Negocio con cuenta nueva' })).toContainText('Nueva Administradora')
    await admin.getByRole('button', { name: 'Cerrar sesión', exact: true }).first().click()
    await admin.goto('/login')
    await admin.getByLabel('Correo electrónico').fill(newEmail)
    await admin.getByLabel('Contraseña', { exact: true }).fill(initialPassword)
    await admin.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
    await expect(admin.getByRole('link', { name: 'Cambiar contraseña ahora' })).toBeVisible()
    await admin.getByRole('link', { name: 'Cambiar contraseña ahora' }).click()
    await admin.getByLabel('Contraseña actual', { exact: true }).fill(initialPassword)
    await admin.getByLabel('Nueva contraseña', { exact: true }).fill('Personal-password-123!')
    await admin.getByLabel('Confirmar nueva contraseña', { exact: true }).fill('Personal-password-123!')
    await admin.getByRole('button', { name: 'Cambiar contraseña', exact: true }).click()
    await expect(admin.getByRole('dialog')).toContainText('Contraseña actualizada')
    await admin.getByRole('dialog').getByRole('button', { name: 'Entendido' }).click()
    await expect(admin.getByRole('link', { name: 'Cambiar contraseña ahora' })).toHaveCount(0)
    await admin.reload()
    await expect(admin.getByRole('heading', { name: 'Seguridad de mi cuenta' })).toBeVisible()
    await expect(admin.getByRole('link', { name: 'Cambiar contraseña ahora' })).toHaveCount(0)

    await admin.goto('/profesionales')
    await admin.getByRole('button',{name:'Registrar profesional',exact:true}).click()
    await admin.getByLabel('Nombre del profesional', { exact: true }).fill('Pro')
    await admin.getByLabel('Apellido del profesional').fill('Nuevo')
    const proEmail = `pro-${id}@example.test`
    await admin.getByLabel('Correo del profesional').fill(proEmail)
    await admin.getByLabel('Teléfono del profesional').fill('70000000')
    const proPassword = await admin.getByLabel('Contraseña inicial', { exact: true }).inputValue()
    await admin.getByRole('dialog').getByRole('button', { name: 'Registrar profesional', exact: true }).click()
    await expect(admin.getByText(`Cuenta creada: ${proEmail}`, { exact: true })).toBeVisible()
    await admin.getByRole('button',{name:'Cerrar',exact:true}).click()
    await admin.getByRole('button', { name: 'Cerrar sesión', exact: true }).first().click()
    await admin.goto('/login')
    await admin.getByLabel('Correo electrónico').fill(proEmail)
    await admin.getByLabel('Contraseña', { exact: true }).fill(proPassword)
    await admin.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
    await expect(admin.getByRole('link', { name: 'Cambiar contraseña ahora' })).toBeVisible()
  } finally { await adminContext.close(); await env.cleanup() }
})
