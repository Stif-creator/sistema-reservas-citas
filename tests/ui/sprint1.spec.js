import { test, expect } from '@playwright/test'
import { initializeTestEnvironment } from '@firebase/rules-unit-testing'
import { collection, deleteDoc, doc, getDocs, query, setDoc, where } from 'firebase/firestore'
import { readFile } from 'node:fs/promises'

test.use({ actionTimeout: 15000 })

test('administrator registers professionals, assigns services/hours, manages roles and applies blocks', async ({ page, browser }) => {
  test.setTimeout(120000)
  const suffix = Date.now()
  const email = `managed-${suffix}@example.test`
  const password = 'test-password'
  const future = new Date()
  future.setUTCDate(future.getUTCDate() + 14)
  while (future.getUTCDay() !== 1) future.setUTCDate(future.getUTCDate() + 1)
  const date = future.toISOString().slice(0, 10)

  const seedBusinessId = `sprint1-${suffix}`
  const signup = await fetch('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signUp?key=demo-key', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: `admin-${suffix}@example.test`, password, returnSecureToken: true }) })
  expect(signup.ok).toBe(true)
  const { localId: uid } = await signup.json()
  const setup = await initializeTestEnvironment({ projectId: 'demo-citaspro', firestore: { host: '127.0.0.1', port: 8080, rules: await readFile('firestore.rules', 'utf8') } })
  await setup.withSecurityRulesDisabled(async context => {
    const db = context.firestore()
    await setDoc(doc(db, 'businesses', seedBusinessId), { ownerUserId: uid, name: 'Negocio Sprint Uno', status: 'active', weeklyHours: Object.fromEntries(Array.from({ length: 7 }, (_, index) => [String(index + 1), [{ start: '09:00', end: '17:00' }]])), settings: { publicPageEnabled: true, timezone: 'America/La_Paz', currencyCode: 'BOB', minAdvanceMinutes: 0, maxAdvanceDays: 90 } })
    await setDoc(doc(db, 'users', uid), { id: uid, auth_uid: uid, firstName: 'Ana', lastName: 'Propietaria', email: `admin-${suffix}@example.test`, status: 'active', globalRole: 'user', businessIds: [seedBusinessId], defaultBusinessId: seedBusinessId, onboardingComplete: true })
    await setDoc(doc(db, 'memberships', `${seedBusinessId}_${uid}`), { userId: uid, businessId: seedBusinessId, role: 'admin', status: 'active' })
  })
  await setup.cleanup()
  await page.goto('/login')
  await page.getByLabel(/Correo/).fill(`admin-${suffix}@example.test`)
  await page.getByLabel(/Contrase/).fill(password)
  await page.getByRole('button', { name: /Iniciar sesi/ }).click()
  await expect(page).toHaveURL(/dashboard$/)
  await expect(page.getByRole('heading', { name: 'Hola, Ana' })).toBeVisible()

  await page.getByRole('link', { name: 'Configuración', exact: true }).click()
  const businessId = (await page.locator('a[target="_blank"]').getAttribute('href')).split('/').pop()
  await page.getByRole('tab', { name: 'Horarios', exact: true }).click()
  await page.getByLabel('Lunes, inicio de franja 1').fill('09:00')
  await page.getByLabel('Lunes, fin de franja 1').fill('12:00')
  await page.getByRole('button', { name: 'Agregar franja' }).first().click()
  await page.getByLabel('Lunes, inicio de franja 2').fill('14:00')
  await page.getByLabel('Lunes, fin de franja 2').fill('17:00')
  await page.getByRole('button', { name: 'Guardar horario', exact: true }).click()
  await expect(page.getByText('Horario guardado.', { exact: true })).toBeVisible()

  await page.getByRole('link', { name: 'Categorías', exact: true }).click()
  await page.getByRole('button', { name: 'Nueva categoría', exact: true }).click()
  await page.getByLabel('Nombre', { exact: true }).fill('Bienestar')
  await page.getByRole('button', { name: 'Crear categoría' }).click()
  await expect(page.getByText('Categoría creada', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Servicios', exact: true }).click()
  await expect(page.locator('#catName')).toHaveCount(0)
  await page.getByRole('button', { name: 'Nuevo servicio' }).click()
  await page.locator('#service-name').fill('Consulta')
  await page.locator('#service-category').selectOption({ label: 'Bienestar' })
  await page.locator('#service-price').fill('100')
  await page.locator('#service-duration').fill('30')
  await page.getByRole('button', { name: 'Crear servicio' }).click()
  await expect(page.getByText('Servicio creado', { exact: true })).toBeVisible()

  const publicPage = await browser.newPage()
  await publicPage.goto(`http://127.0.0.1:4173/b/${businessId}`)
  await expect(publicPage.getByRole('heading', { name: 'Consulta', exact: true })).toBeVisible()
  const serviceRow = page.getByRole('row').filter({ hasText: 'Consulta' })
  await serviceRow.getByRole('button', { name: 'Editar', exact: true }).click()
  await page.locator('#service-name').fill('Consulta actualizada')
  await page.locator('#service-price').fill('125.50')
  await page.locator('#service-duration').fill('45')
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(page.getByText('Servicio actualizado', { exact: true })).toBeVisible()
  await expect(publicPage.getByRole('heading', { name: 'Consulta actualizada', exact: true })).toBeVisible()
  await publicPage.close()
  await page.reload()
  await expect(serviceRow).toContainText('Consulta actualizada')
  await expect(serviceRow).toContainText('125.5 BOB')
  await expect(serviceRow).toContainText('45 min')
  await serviceRow.getByRole('button', { name: 'Editar', exact: true }).click()
  await page.locator('#service-name').fill('Consulta')
  await page.locator('#service-price').fill('100')
  await page.locator('#service-duration').fill('30')
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(page.getByText('Servicio actualizado', { exact: true })).toBeVisible()

  // An old imported document may contain another document's embedded id.
  // Editing it must target its actual Firestore path, not that stored field.
  const env = await initializeTestEnvironment({ projectId: 'demo-citaspro', firestore: {
    host: '127.0.0.1', port: 8080, rules: await readFile('firestore.rules', 'utf8'),
  } })
  try {
    await env.withSecurityRulesDisabled(async (context) => {
      const db = context.firestore()
      const snapshot = await getDocs(query(collection(db, 'services'), where('businessId', '==', businessId)))
      const original = snapshot.docs[0]
      await setDoc(doc(db, 'services', `legacy-${suffix}`), { ...original.data(), id: original.id, name: 'Servicio demo 01' })
    })
  } finally { await env.cleanup() }
  const demoRow = page.getByRole('row').filter({ hasText: 'Servicio demo 01' })
  await demoRow.getByRole('button', { name: 'Editar', exact: true }).click()
  await page.locator('#service-price').fill('200')
  await page.locator('#service-duration').fill('60')
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(demoRow).toContainText('200 BOB')
  await expect(demoRow).toContainText('60 min')
  await expect(serviceRow).toContainText('100 BOB')
  await page.reload()
  await expect(demoRow).toContainText('200 BOB')

  await page.getByRole('link', { name: 'Profesionales', exact: true }).click()
  await page.getByRole('button',{name:'Registrar profesional',exact:true}).click()
  async function fillProfessional() {
    await page.getByLabel('Nombre del profesional', { exact: true }).fill('Luis')
    await page.getByLabel('Apellido del profesional').fill('Prueba')
    await page.getByLabel('Correo del profesional').fill(email)
    await page.getByLabel('Teléfono del profesional').fill('70000001')
    await page.getByLabel('Contraseña inicial', { exact: true }).fill(password)
    await page.getByRole('textbox', { name: 'Confirmar contraseña inicial', exact: true }).fill(password)
  }
  await fillProfessional()
  await page.getByRole('dialog').getByRole('button', { name: 'Registrar profesional', exact: true }).click()
  await expect(page.getByText('Profesional registrado y activo.', { exact: false })).toBeVisible()
  // A duplicate account fails clearly and leaves the owner signed in.
  await fillProfessional()
  await page.getByRole('dialog').getByRole('button', { name: 'Registrar profesional', exact: true }).click()
  await expect(page.getByText('Ese correo ya está registrado.')).toBeVisible()
  // The existing project includes profiles such as professional_001, with no id field.
  const legacyEnv = await initializeTestEnvironment({ projectId: 'demo-citaspro', firestore: {
    host: '127.0.0.1', port: 8080, rules: await readFile('firestore.rules', 'utf8'),
  } })
  try {
    await legacyEnv.withSecurityRulesDisabled(async (context) => {
      const db = context.firestore()
      const profiles = await getDocs(query(collection(db, 'professionals'), where('businessId', '==', businessId)))
      const original = profiles.docs[0]
      const data = { ...original.data(), serviceIds: ['deleted-service'] }
      delete data.id
      await setDoc(doc(db, 'professionals', `professional_001-${suffix}`), data)
      await deleteDoc(original.ref)
    })
  } finally { await legacyEnv.cleanup() }
  await page.reload()
  await expect(page.getByRole('button', { name: 'Gestionar', exact: true })).toHaveCount(1)
  await page.getByRole('button', { name: 'Gestionar', exact: true }).click()
  await page.getByRole('tab',{name:'Servicios',exact:true}).click()
  await page.getByRole('checkbox', { name: /Consulta Bienestar/ }).check()
  await page.getByRole('button', { name: 'Guardar servicios', exact: true }).click()
  await expect(page.getByText('Servicios asignados actualizados.')).toBeVisible()
  await page.getByRole('tab',{name:'Horarios',exact:true}).click()
  await page.getByRole('switch', { name:'Abrir Lunes', exact:true }).click()
  await page.getByLabel('Lunes, inicio de franja 1').fill('09:00')
  await page.getByLabel('Lunes, fin de franja 1').fill('12:00')
  await page.getByRole('button', { name: 'Agregar franja' }).first().click()
  await page.getByLabel('Lunes, inicio de franja 2').fill('14:00')
  await page.getByLabel('Lunes, fin de franja 2').fill('17:00')
  await page.getByRole('button', { name: 'Guardar horario', exact: true }).click()
  await expect(page.getByText('Horario guardado.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Copiar a otros días', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Martes', exact: true }).check()
  await page.getByRole('button', { name: 'Confirmar y copiar', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name:'Confirmar copia', exact:true }).click()
  await expect(page.getByLabel('Martes, inicio de franja 1')).toHaveValue('09:00')
  await page.getByRole('button', { name: 'Guardar horario', exact: true }).click()
  await expect(page.getByText('Horario guardado.', { exact: true })).toBeVisible()
  await page.screenshot({ path:'test-results/professional-editor-desktop.png', fullPage:true })
  await page.setViewportSize({width:390,height:844})
  await expect(page.getByRole('dialog')).toBeVisible()
  expect(await page.getByRole('dialog').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path:'test-results/professional-editor-mobile.png', fullPage:true })
  await page.setViewportSize({width:1280,height:900})
  await page.getByRole('button', { name: 'Cerrar', exact: true }).click()

  const context = await browser.newContext()
  const professional = await context.newPage()
  try {
    await professional.goto('http://127.0.0.1:4173/login')
    await professional.getByLabel('Correo electrónico').fill(email)
    await professional.getByLabel('Contraseña', { exact: true }).fill(password)
    await professional.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
    await expect(professional.getByRole('heading', { name:'Por seguridad, cambia tu contraseña' })).toBeVisible()
    const newPassword = 'New-secure-test-2026!'
    await professional.getByLabel('Contraseña actual', { exact:true }).fill(password)
    await professional.getByLabel('Nueva contraseña', { exact:true }).fill(newPassword)
    await professional.getByLabel('Confirmar nueva contraseña', { exact:true }).fill(newPassword)
    await professional.getByRole('button', { name:'Guardar nueva contraseña', exact:true }).click()
    await expect(professional).toHaveURL(/dashboard$/)
    await expect(professional.getByRole('heading', { name: 'Hola, Luis' })).toBeVisible()
    await professional.goto('http://127.0.0.1:4173/usuarios')
    await expect(professional).toHaveURL(/\/dashboard$/)
    await professional.getByRole('link', { name: 'Mis servicios', exact: true }).click()
    await expect(professional.getByRole('heading', { name: 'Mis servicios', exact: true })).toBeVisible()
    const assignedService = professional.locator('.service-card').filter({ hasText: 'Consulta' })
    await expect(assignedService).toBeVisible()
    await assignedService.getByRole('button', { name: 'Ver detalles' }).click()
    await expect(professional.getByRole('dialog', { name: 'Consulta' })).toBeVisible()
    await expect(professional.getByText('Asignado a tu perfil')).toBeVisible()
    await expect(professional.getByRole('button', { name: 'Editar' })).toHaveCount(0)
    await professional.getByRole('button', { name: 'Cerrar', exact: true }).click()
    await professional.getByRole('link', { name: 'Mi disponibilidad', exact: true }).click()
    await professional.getByLabel('Servicio', { exact: true }).selectOption({ label: 'Consulta' })
    await professional.getByLabel('Fecha de inicio', { exact: true }).fill(date)
    const firstOpenDay = Number(date.slice(-2))
    await professional.getByRole('region', { name:'Calendario de disponibilidad' })
      .getByRole('button', { name:new RegExp(`^lunes, ${firstOpenDay} de`) }).click()
    const available = professional.getByRole('group', { name:'Horarios disponibles', exact:true })
    await expect(available.getByText('10:00', { exact: true })).toBeVisible()

    await professional.getByRole('link', { name: 'Bloqueos', exact: true }).click()
    await expect(professional.getByRole('heading', { name:'Bloqueos', exact:true })).toBeVisible()
    await professional.getByRole('button', { name:'Nuevo bloqueo', exact:true }).click()
    await professional.getByLabel('Título', { exact: true }).fill('Descanso solicitado')
    await professional.getByLabel('Primer día', { exact: true }).fill(date)
    await professional.getByLabel('Último día (incluido)', { exact: true }).fill(new Date(Date.parse(date) + 86400000).toISOString().slice(0, 10))
    await professional.getByRole('button', { name: 'Enviar solicitud', exact:true }).click()
    await expect(professional.getByText('Solicitud enviada al administrador.', { exact: true })).toBeVisible()
    await page.getByRole('link', { name: 'Avisos', exact: true }).click()
    await expect(page.getByRole('heading', { name: /Solicitud de bloqueo/ })).toBeVisible()
    await page.goto('/bloqueos')
    const pendingBlock = page.getByRole('row').filter({ hasText:'Descanso solicitado' })
    await expect(pendingBlock).toBeVisible()
    await pendingBlock.getByRole('button', { name: 'Aprobar', exact: true }).click()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Aprobar' }).click()
    await expect(page.getByText('Aprobado', { exact: true })).toBeVisible()
    await professional.getByRole('link', { name: 'Mi disponibilidad', exact: true }).click()
    await professional.getByLabel('Servicio', { exact: true }).selectOption({ label: 'Consulta' })
    await professional.getByLabel('Fecha de inicio', { exact: true }).fill(date)
    await professional.getByRole('region', { name:'Calendario de disponibilidad' })
      .getByRole('button', { name:new RegExp(`^lunes, ${firstOpenDay} de`) }).click()
    await expect(available.getByText('10:00', { exact: true })).toHaveCount(0)
    const approvedBlock = page.getByRole('row').filter({ hasText:'Descanso solicitado' })
    await approvedBlock.getByRole('button', { name:'Cancelar', exact:true }).click()
    await page.getByRole('alertdialog').getByRole('button', { name:'Eliminar', exact:true }).click()
    await professional.reload()
    await professional.getByLabel('Servicio', { exact:true }).selectOption({ label:'Consulta' })
    await professional.getByLabel('Fecha de inicio', { exact:true }).fill(date)
    await professional.getByRole('region', { name:'Calendario de disponibilidad' })
      .getByRole('button', { name:new RegExp(`^lunes, ${firstOpenDay} de`) }).click()
    await expect(professional.getByRole('group', { name:'Horarios disponibles', exact:true })).toBeVisible()
    await expect(available.getByText('10:00', { exact: true })).toBeVisible()

    await page.getByRole('link', { name: 'Usuarios', exact: true }).click()
    await expect(page.getByLabel('Estado de Ana Propietaria')).toBeDisabled()
    const row = page.getByRole('row').filter({ hasText: 'Luis Prueba' })
    await row.getByLabel('Rol de Luis Prueba').selectOption('client')
    await row.getByRole('button', { name: 'Guardar', exact: true }).click()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Actualizar acceso', exact: true }).click()
    await expect(page.getByText('Los cambios se guardaron para esta membresía.', { exact: true })).toBeVisible()
    await expect(professional).toHaveURL(/\/cliente$/)
    await expect(professional.getByRole('link', { name: 'Bloqueos', exact: true })).toHaveCount(0)

    await row.getByLabel('Rol de Luis Prueba').selectOption('professional')
    await row.getByRole('button', { name: 'Guardar', exact: true }).click()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Actualizar acceso', exact: true }).click()
    await expect(professional.getByRole('link', { name: 'Bloqueos', exact: true })).toBeVisible()
    await row.getByLabel('Estado de Luis Prueba').selectOption('inactive')
    await row.getByRole('button', { name: 'Guardar', exact: true }).click()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Actualizar acceso', exact: true }).click()
    await expect(professional.getByText('Tu cuenta o membresía no está activa.', { exact: false })).toBeVisible()

    await row.getByLabel('Rol de Luis Prueba').selectOption('professional')
    await row.getByLabel('Estado de Luis Prueba').selectOption('active')
    await row.getByRole('button', { name: 'Guardar', exact: true }).click()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Actualizar acceso', exact: true }).click()
    await expect(professional.getByRole('heading', { name: 'Hola, Luis' })).toBeVisible()
    await professional.getByRole('link', { name: 'Mi disponibilidad', exact: true }).click()
    await professional.getByLabel('Servicio', { exact: true }).selectOption({ label: 'Consulta' })
    await professional.getByLabel('Fecha de inicio', { exact: true }).fill(date)
    await professional.getByRole('region', { name:'Calendario de disponibilidad' })
      .getByRole('button', { name:new RegExp(`^lunes, ${firstOpenDay} de`) }).click()
    await expect(professional.getByRole('group', { name:'Horarios disponibles', exact:true }).getByText('10:00', { exact: true })).toBeVisible()
  } finally { await context.close().catch(() => {}) }
})
