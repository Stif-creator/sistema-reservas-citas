import { test, expect } from '@playwright/test'
import { initializeTestEnvironment } from '@firebase/rules-unit-testing'
import { doc, setDoc, deleteDoc } from 'firebase/firestore'
import { readFile } from 'node:fs/promises'

test('lists search across pages, update live and keep categories separate', async ({ page }) => {
  test.setTimeout(120000)
  const id = `lists-${Date.now()}`, email = `${id}@example.test`, password = 'test-password'
  const response = await fetch('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signUp?key=demo-key', {
    method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email, password, returnSecureToken: true }),
  })
  expect(response.ok).toBe(true)
  const { localId: uid } = await response.json()
  const env = await initializeTestEnvironment({ projectId: 'demo-citaspro', firestore: { host: '127.0.0.1', port: 8080, rules: await readFile('firestore.rules', 'utf8') } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  try {
    await env.withSecurityRulesDisabled(async context => {
      const db = context.firestore()
      await setDoc(doc(db, 'businesses', id), { ownerUserId: uid, name: 'Negocio Listas', status: 'active', settings: { currencyCode: 'BOB', timezone: 'America/La_Paz' } })
      await setDoc(doc(db, 'users', uid), { firstName: 'Ana', lastName: 'Listas', email, status: 'active', globalRole: 'user', businessIds: [id], onboardingComplete: true })
      await setDoc(doc(db, 'memberships', `${id}_${uid}`), { userId: uid, businessId: id, role: 'admin', status: 'active', permissions: {} })
      const otherBusiness = `${id}-other`, professionalId = `professional-${id}`
      await setDoc(doc(db, 'businesses', otherBusiness), { ownerUserId: `owner-${otherBusiness}`, status: 'active' })
      await setDoc(doc(db, 'users', professionalId), { firstName: 'Profesional', lastName: 'Multiempresa', email: `professional-${id}@example.test`, status: 'active', globalRole: 'user', businessIds: [otherBusiness, id] })
      await setDoc(doc(db, 'memberships', `${id}_${professionalId}`), { userId: professionalId, businessId: id, role: 'professional', status: 'active' })
      await setDoc(doc(db, 'memberships', `${otherBusiness}_${professionalId}`), { userId: professionalId, businessId: otherBusiness, role: 'professional', status: 'active' })
      for (let index = 1; index <= 12; index++) {
        const clientId = `client-${id}-${index}`
        await setDoc(doc(db, 'users', clientId), { firstName: `Cliente ${String(index).padStart(2, '0')}`, lastName: 'Prueba', email: `${clientId}@example.test`, status: 'active', globalRole: 'user', businessIds: [id] })
        await setDoc(doc(db, 'memberships', `${id}_${clientId}`), { userId: clientId, businessId: id, role: 'client', status: index === 12 ? 'inactive' : 'active' })
      }
      await setDoc(doc(db, 'categories', id), { businessId: id, name: 'Odontología', displayOrder: 1, isActive: true })
      for (let i = 1; i <= 23; i++) {
        await setDoc(doc(db, 'services', `${id}-${i}`), { businessId: id, categoryId: id, name: `Consulta ${String(i).padStart(2, '0')}`, price: 100, durationMinutes: 30, isActive: true })
      }
    })
    await page.goto('/login')
    await page.getByLabel('Correo electrónico').fill(email)
    await page.getByLabel('Contraseña', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
    await expect(page).toHaveURL(/dashboard/)
    await page.getByRole('link', { name: 'Servicios', exact: true }).click()
    const list = page.getByRole('region', { name: 'Servicios', exact: true })
    await expect(list.locator('tbody tr')).toHaveCount(10)
    await page.screenshot({ path: 'test-results/admin-services-desktop.png', fullPage: true })
    await list.getByRole('button', { name: 'Siguiente' }).click()
    await expect(list).toContainText('Página 2 de 3')
    await expect(list.locator('tbody tr').first()).toContainText('Consulta 11')
    await list.getByRole('searchbox').fill('consulta 23')
    await expect(list.locator('tbody tr')).toHaveCount(1)
    await expect(list).toContainText('Página 1 de 1')
    await list.getByRole('searchbox').fill('odontologia')
    await expect(list.locator('tbody tr')).toHaveCount(10)
    await list.getByRole('combobox').selectOption('25')
    await expect(list.locator('tbody tr')).toHaveCount(23)
    await list.getByRole('searchbox').fill('inexistente')
    await expect(list.getByText('No hay resultados para esta selección.')).toBeVisible()
    await list.getByRole('searchbox').fill('nueva')
    await env.withSecurityRulesDisabled(context => setDoc(doc(context.firestore(), 'services', `${id}-live`), { businessId: id, categoryId: id, name: 'Nueva consulta', price: 90, durationMinutes: 30, isActive: true }))
    await expect(list.locator('tbody tr')).toHaveCount(1)
    await env.withSecurityRulesDisabled(context => deleteDoc(doc(context.firestore(), 'services', `${id}-live`)))
    await expect(list.locator('tbody tr')).toHaveCount(0)
    await expect(page.locator('#catName')).toHaveCount(0)
    await list.getByRole('searchbox').fill('')
    await page.getByRole('searchbox', { name: 'Buscar en las listas de esta página' }).fill('Consulta 23')
    await expect(list.locator('tbody tr')).toHaveCount(1)
    await page.getByRole('link', { name: 'Categorías', exact: true }).click()
    await expect(page.locator('#catName')).toBeVisible()
    await expect(page.locator('#svcName')).toHaveCount(0)
    await page.getByRole('region', { name: 'Categorías', exact: true }).getByRole('searchbox').fill('odontologia')
    await expect(page.locator('tbody tr')).toHaveCount(1)
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: 'test-results/admin-categories-mobile.png', fullPage: true })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto('/usuarios')
    const usersList = page.getByRole('region', { name: 'Usuarios', exact: true })
    await expect(usersList.locator('tbody tr')).toHaveCount(10)
    await expect(page.locator('.admin-summary-item').filter({ hasText: 'Administradores' })).toContainText('1')
    await expect(page.locator('.admin-summary-item').filter({ hasText: 'Profesionales' })).toContainText('1')
    await expect(page.locator('.admin-summary-item').filter({ hasText: 'Clientes' })).toContainText('12')
    await usersList.getByRole('button', { name: 'Siguiente' }).click()
    await expect(usersList.locator('tbody tr')).toHaveCount(4)
    await expect(usersList.locator('tbody tr')).toContainText('Profesional Multiempresa')
    await expect(page.getByText('Cuenta protegida', { exact: true })).toBeVisible()
    await page.getByLabel('Filtrar por rol').selectOption('professional')
    await expect(usersList.locator('tbody tr')).toHaveCount(1)
    await expect(usersList.locator('tbody tr')).toContainText('Profesional Multiempresa')
    await usersList.getByRole('searchbox').fill('multiempresa')
    await expect(usersList.locator('tbody tr')).toHaveCount(1)
    await usersList.getByRole('searchbox').fill('sin coincidencias')
    await expect(usersList.locator('tbody tr')).toHaveCount(0)
    await usersList.getByRole('searchbox').fill('')
    await page.getByLabel('Filtrar por rol').selectOption('admin')
    await expect(usersList.locator('tbody tr')).toHaveCount(1)
    await page.getByLabel('Filtrar por estado').selectOption('inactive')
    await expect(usersList.locator('tbody tr')).toHaveCount(0)
    await page.getByLabel('Filtrar por estado').selectOption('active')
    await expect(usersList.locator('tbody tr')).toHaveCount(1)
    await expect(usersList.locator('tbody tr')).toContainText('Administrador')
    await expect(page.getByLabel('Rol de Ana Listas')).toHaveCount(0)
    await page.screenshot({ path: 'test-results/admin-users-desktop.png', fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: 'test-results/admin-users-mobile.png', fullPage: true, animations: 'disabled' })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto('/negocio')
    await expect(page.getByLabel('Nombre', { exact: true })).toBeDisabled()
    await expect(page.getByRole('complementary', { name: 'Vista previa del negocio' }).filter({ visible: true })).toContainText('Negocio Listas')
    await page.getByRole('tab', { name: 'Imágenes', exact: true }).click()
    await expect(page.getByLabel('Portada', { exact: true })).toBeVisible()
    await page.getByRole('tab', { name: 'Página nosotros', exact: true }).click()
    await page.getByLabel('Título de Nosotros').fill('Un lugar para ti')
    await expect(page.getByRole('heading', { name: 'Un lugar para ti', exact: true })).toBeVisible()
    await page.getByRole('tab', { name: 'Contacto', exact: true }).click()
    await page.getByLabel('Email', { exact: true }).fill('invalido')
    await page.getByRole('tab', { name: 'Datos generales', exact: true }).click()
    await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
    await expect(page.getByRole('tab', { name: 'Contacto', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByText('Ingresa un email válido.')).toBeVisible()
    await page.getByLabel('Email', { exact: true }).fill('contacto@example.test')
    await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
    await expect(page.getByText('Cambios guardados.', { exact: true })).toBeVisible()
    await page.reload()
    await expect(page.getByLabel('Nombre', { exact: true })).toHaveValue('Negocio Listas')
    await page.screenshot({ path: 'test-results/settings-desktop.png', fullPage: true })
    await page.getByRole('tab', { name: 'Horarios', exact: true }).click()
    await page.getByRole('button', { name: 'Agregar franja' }).first().click()
    await page.getByLabel('Lunes, inicio de franja 1').fill('09:00')
    await page.getByLabel('Lunes, fin de franja 1').fill('13:00')
    await page.getByRole('button', { name: 'Guardar horario', exact: true }).click()
    await expect(page.getByText('Horario guardado.', { exact: true })).toBeVisible()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: 'test-results/settings-mobile.png', fullPage: true, animations: 'disabled' })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(errors).toEqual([])
  } finally { await env.cleanup() }
})
